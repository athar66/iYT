'use strict';
const fs=require('fs'),path=require('path'),os=require('os'),assert=require('assert'),cp=require('child_process');
const AudioFiles=require('../source/native/iyt-daemon/audio-files');
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'iyt-audio-access-'));
fs.chmodSync(tmp,0o711);
const cache=path.join(tmp,'cache'),video=path.join(cache,'testvideo01');
fs.mkdirSync(cache,0o711);fs.mkdirSync(video,0o700);
const source=path.join(video,'audio.m4a');fs.writeFileSync(source,'completed audio',{mode:0o600});
const opts={cacheDir:cache,log:function(){}};
const files=new AudioFiles(opts),published=files.publish(source);
assert.equal(fs.statSync(video).mode&0o777,0o700);
assert.equal(fs.statSync(published).ino,fs.statSync(source).ino);
assert.equal(fs.statSync(published).mode&0o777,0o644);
assert.equal(fs.statSync(path.dirname(published)).mode&0o777,0o711);
assert.equal(files.publish(source),published);
if(process.getuid&&process.getuid()===0){
    const ids={uid:65534,gid:65534,encoding:'utf8'};
    assert.notEqual(cp.spawnSync('/bin/cat',[source],ids).status,0);
    const read=cp.spawnSync('/bin/cat',[published],ids);
    assert.equal(read.status,0,read.stderr);assert.equal(read.stdout,'completed audio');
    console.log('Cross-account proof: private cache denied; audio handoff readable by another uid.');
}else console.log('Cross-uid read requires root; file modes and inode identity verified.');
files.clear();assert(!fs.existsSync(published));assert(fs.existsSync(source));
const first=new AudioFiles(opts),stale=first.publish(source);
const recovered=new AudioFiles(opts),fresh=recovered.publish(source);
assert(!fs.existsSync(stale));assert(fs.existsSync(fresh));recovered.clear();
const protect=new AudioFiles(opts),replaced=protect.publish(source);
fs.unlinkSync(replaced);fs.writeFileSync(replaced,'different inode');protect.clear();
assert.equal(fs.readFileSync(replaced,'utf8'),'different inode');
const symlink=path.join(video,'audio.head.m4a');fs.symlinkSync(source,symlink);
assert.throws(()=>new AudioFiles(opts).publish(symlink),/invalid completed audio/);
console.log('Audio export: no media copy, private cache preserved, cleanup/recovery and ownership guards passed.');
