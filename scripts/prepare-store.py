"""Prepare verified tool payload and repository manifest. No vehicle writes."""
from pathlib import Path
import hashlib
import json
import shutil
import urllib.request

r = Path(__file__).resolve().parents[1]
d = r/'source/native/iyt-daemon'
prebuilt = d/'prebuilt'
prebuilt.mkdir(exist_ok=True)
version = '2026.10.26'
expected = 'e51e69e89489f199530f13d32a4342da3ddb2cf34842f364603a066db05afbf3'
zipapp = prebuilt/'ytdlp.pyz'
if not zipapp.exists() or hashlib.sha256(zipapp.read_bytes()).hexdigest() != expected:
    url = f'https://github.com/yt-dlp/yt-dlp/releases/download/{version}/yt-dlp'
    with urllib.request.urlopen(url, timeout=90) as response:
        data = response.read()
    if hashlib.sha256(data).hexdigest() != expected:
        raise SystemExit('Official extractor digest mismatch; refusing to stage')
    zipapp.write_bytes(data)
# Official source zipapp runs under the target Python3.12. No host-generated bytecode.
(prebuilt/'extractor.json').write_text(json.dumps({'version': version, 'sha256': expected, 'format': 'official source zipapp; no host bytecode'}, indent=2)+'\n')
component = json.loads((d/'component.json').read_text())
component['requires'].pop('jap-node22', None)
for name, origin, mode in [('network.js','network.js','0644'), ('audio-files.js','audio-files.js','0644'), ('qjs','prebuilt/qjs','0755'), ('QuickJS-MIT.txt','QuickJS-MIT.txt','0644')]:
    if not any(f['path'] == name for f in component['files']):
        component['files'].append({'path':name,'from':origin,'mode':mode})
shutil.copy2(r/'licenses/QuickJS-MIT.txt',d/'QuickJS-MIT.txt')
shutil.copy2(r/'source/LICENSE', d/'LICENSE')
shutil.copy2(r/'source/THIRD_PARTY_LICENSES', d/'THIRD_PARTY_LICENSES')
for file in component['files']:
    if file['path'] in ['ytdec', 'ytdlp.pyz']:
        file['from'] = 'prebuilt/'+file['path']
    if file['path'] in ['LICENSE', 'THIRD_PARTY_LICENSES']:
        file['from'] = file['path']
if not any(f['path'] == 'iyt-lock' for f in component['files']):
    component['files'].append({'path': 'iyt-lock', 'from': 'prebuilt/iyt-lock', 'mode': '0755'})
component['files'].append({'path': 'extractor.json', 'from': 'prebuilt/extractor.json', 'mode': '0644'}) if not any(f['path'] == 'extractor.json' for f in component['files']) else None
(d/'component.json').write_text(json.dumps(component, indent=2)+'\n')
manifest = {'schema': 1, 'components': [
    {'id': 'iyt_app', 'kind': 'app', 'path': 'source/apps/iyt_app', 'title': 'iYT',
     'description': 'YouTube for BMW iDrive 7 with native audio and hardware H.264 video.',
     'mguHmi': ['ID7'], 'requires': {'iyt-daemon': '0.5.6', 'mgu-render': '0.6.11', 'mgu-inputgate': '1.0.0'},
     'build': {'python': 'source/kit/tools/build.py', 'args': ['{id}'], 'sdk': 'source/oap-sdk',
               'output': 'source/dist/{id}@{version}.tgz'}},
    {'id': 'iyt-daemon', 'kind': 'tool', 'path': 'source/native/iyt-daemon', 'title': 'iYT playback service', 'mguHmi': ['ID7'], 'uninstallable': True}
]}
(r/'mgu-repo.json').write_text(json.dumps(manifest, indent=2)+'\n')
(r/'mgu-store.json').write_text(json.dumps({'apps': {'iyt_app': {'title': 'iYT', 'description': manifest['components'][0]['description'], 'author': 'athar66', 'icon': 'iyt_app.png'}}}, indent=2)+'\n')
print('Prepared mgu-repo.json for branch discovery and verified official extractor payload.')
